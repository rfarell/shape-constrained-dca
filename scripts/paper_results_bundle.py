LEVELS = ("0.8", "0.9", "0.95")


def load(path):
    return json.loads(Path(path).read_text())


def metrics_table(results, labels, source):
    rows = [f"Source: `{source}`", "",
            "| Model | WIS orig15 | R² orig15 | WIS origin0 | WIS all28 | Cov 80/90/95 (all28, %) | Width80/95 (scaled, all28) | Energy orig15 | Variogram orig15 | Phase WIS o/g/w (orig15) | MAE o (BBL) / g (MCF) / w (BBL) (orig15) |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for label in labels:
        if label not in results:
            continue
        r = results[label]
        o15, a28 = r["original15"], r["all28"]
        cov = " / ".join(f"{100 * r['coverage'][lv]['macro_all28']:.1f}" for lv in LEVELS)
        pp = o15["per_phase"]
        rows.append(f"| {NAMES.get(label, label)} | {r['wis_original15']:.4f} | {r['r2_original15']:.3f} | {r['wis_origin0']:.4f} | "
                    f"{r['wis_all28']:.4f} | {cov} | {a28['macro_scaled_width_80']:.3f} / {a28['macro_scaled_width_95']:.3f} | "
                    f"{o15['joint']['mean_energy_score']:.4f} | {o15['joint']['mean_variogram_score_p05']:.4f} | "
                    + " / ".join(f"{pp[p]['scaled_wis']:.3f}" for p in ("oil", "gas", "water")) + " | "
                    + " / ".join(f"{pp[p]['mae']:.0f}" for p in ("oil", "gas", "water")) + " |")
    return "\n".join(rows)


def comparisons_table(comparisons, candidate, source):
    rows = [f"Source: `{source}` — relative WIS gain 1 − WIS(candidate)/WIS(reference) in %, paired whole-group bootstrap 95% interval; positive = candidate better", "",
            "| Candidate vs reference | original15 | origin0 | all28 |", "|---|---:|---:|---:|"]
    for key, value in sorted(comparisons.items()):
        if not key.startswith(candidate + "_vs_"):
            continue
        cells = [f"{100 * value[s]['point']:+.2f} ({100 * value[s]['lower95']:+.2f}, {100 * value[s]['upper95']:+.2f})"
                 for s in ("original15", "origin0", "all28")]
        ref = key.split("_vs_", 1)[1]
        rows.append(f"| {NAMES.get(candidate, candidate)} vs {NAMES.get(ref, ref)} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def single_seed(results, prefix):
    vals = sorted((k, v["wis_original15"]) for k, v in results.items() if k.startswith(prefix) and "_seed" in k and "mix" not in k)
    return ", ".join(f"{k.split('_seed')[1]}: {v:.4f}" for k, v in vals)


